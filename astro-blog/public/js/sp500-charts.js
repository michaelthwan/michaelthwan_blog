/* ============================================
   CHART.JS CUSTOM PLUGIN — Event Annotations
   Draws labeled markers on the chart canvas.
   Two passes: measure + resolve label collisions, then draw.
   Supports a "spotlight" state (chart.$spotlight = label) that
   emphasizes one event and dims the rest — driven by the
   milestone timeline chips and article headings.
   ============================================ */

function isDarkTheme() {
    return document.documentElement.getAttribute('data-theme') === 'dark';
}

function annotationPalette() {
    // The chart wrap keeps a white background in both themes,
    // so one high-contrast palette works everywhere.
    return {
        bull: { text: '#0d3f12', bg: 'rgba(232,245,233,0.97)', border: '#2e7d32', dot: '#2e7d32' },
        bear: { text: '#7f1010', bg: 'rgba(255,231,232,0.97)', border: '#c62828', dot: '#c62828' },
    };
}

const ANNOTATION_FONT = '600 10.5px Inter, system-ui, sans-serif';

const eventAnnotationPlugin = {
    id: 'eventAnnotations',
    afterDraw(chart) {
        const events = chart.config.options.plugins.eventAnnotations;
        if (!events || !events.length) return;

        const { ctx, chartArea } = chart;
        const meta = chart.getDatasetMeta(0);
        const renderedPoints = meta.data;
        const dataset = chart.data.datasets[0].data;
        const spotlight = chart.$spotlight || null;
        const palette = annotationPalette();

        ctx.save();
        ctx.font = ANNOTATION_FONT;

        const pad = 6;
        const boxH = 20;
        const placed = [];

        // Pass 1: anchor each event to the nearest rendered data point and
        // resolve label overlaps by pushing boxes away from the line.
        const resolved = events.map(event => {
            let nearestIdx = 0;
            let minDist = Infinity;
            for (let i = 0; i < dataset.length; i++) {
                const dist = Math.abs(dataset[i].x - event.year);
                if (dist < minDist) {
                    minDist = dist;
                    nearestIdx = i;
                }
            }
            const xPixel = renderedPoints[nearestIdx].x;
            const yPixel = renderedPoints[nearestIdx].y;
            const isBull = event.type === 'bull';

            const dy = event.dy || (isBull ? -35 : 28);
            const dx = event.dx || 0;
            const boxW = ctx.measureText(event.label).width + pad * 2;

            let boxX = xPixel + dx - boxW / 2;
            if (boxX < chartArea.left) boxX = chartArea.left + 2;
            if (boxX + boxW > chartArea.right) boxX = chartArea.right - boxW - 2;

            let boxY = yPixel + dy - boxH / 2;
            const step = (dy < 0 ? -1 : 1) * (boxH + 3);
            const overlaps = (bx, by) => placed.some(p =>
                bx < p.x + p.w + 2 && bx + boxW + 2 > p.x &&
                by < p.y + p.h + 2 && by + boxH + 2 > p.y);
            let guard = 0;
            while (overlaps(boxX, boxY) && guard < 20) {
                boxY += step;
                guard++;
            }
            // Clamp vertically inside the plot area
            if (boxY < chartArea.top + 2) boxY = chartArea.top + 2;
            if (boxY + boxH > chartArea.bottom - 2) boxY = chartArea.bottom - boxH - 2;
            // If clamping re-introduced an overlap, nudge back toward the line
            guard = 0;
            while (overlaps(boxX, boxY) && guard < 20) {
                boxY -= step;
                guard++;
            }

            placed.push({ x: boxX, y: boxY, w: boxW, h: boxH });
            return { event, xPixel, yPixel, boxX, boxY, boxW, isBull };
        });

        // Pass 2: draw connectors, dots, and labels. When a spotlight is
        // active, draw dimmed events first so the highlighted one sits on top.
        const drawOne = ({ event, xPixel, yPixel, boxX, boxY, boxW, isBull }) => {
            const c = isBull ? palette.bull : palette.bear;
            const isSpot = spotlight !== null && event.label === spotlight;
            const isDim = spotlight !== null && !isSpot;

            ctx.globalAlpha = isDim ? 0.18 : 1;

            const labelCx = boxX + boxW / 2;
            const labelCy = boxY + boxH / 2;
            const above = labelCy < yPixel;

            // Connecting line
            ctx.beginPath();
            ctx.setLineDash([3, 3]);
            ctx.moveTo(xPixel, yPixel);
            ctx.lineTo(labelCx, above ? boxY + boxH : boxY);
            ctx.strokeStyle = c.border;
            ctx.lineWidth = isSpot ? 2 : 1.4;
            ctx.stroke();
            ctx.setLineDash([]);

            // Dot at data point (white halo ring keeps it visible on the line)
            const r = isSpot ? 6 : 4;
            ctx.beginPath();
            ctx.arc(xPixel, yPixel, r + 1.5, 0, Math.PI * 2);
            ctx.fillStyle = '#ffffff';
            ctx.fill();
            ctx.beginPath();
            ctx.arc(xPixel, yPixel, r, 0, Math.PI * 2);
            ctx.fillStyle = c.dot;
            ctx.fill();

            // Label background
            ctx.fillStyle = c.bg;
            ctx.strokeStyle = c.border;
            ctx.lineWidth = isSpot ? 2 : 1.2;
            if (isSpot) {
                ctx.shadowColor = 'rgba(0,0,0,0.25)';
                ctx.shadowBlur = 6;
                ctx.shadowOffsetY = 1;
            }
            ctx.beginPath();
            ctx.roundRect(boxX, boxY, boxW, boxH, 4);
            ctx.fill();
            ctx.shadowColor = 'transparent';
            ctx.shadowBlur = 0;
            ctx.shadowOffsetY = 0;
            ctx.stroke();

            // Label text
            ctx.fillStyle = c.text;
            ctx.textAlign = 'center';
            ctx.textBaseline = 'middle';
            ctx.fillText(event.label, labelCx, labelCy);

            ctx.globalAlpha = 1;
        };

        resolved.filter(r => spotlight === null || r.event.label !== spotlight).forEach(drawOne);
        resolved.filter(r => spotlight !== null && r.event.label === spotlight).forEach(drawOne);

        ctx.restore();
    }
};

/* ============================================
   SPOTLIGHT REGISTRY + MILESTONE TIMELINES
   Each chart gets a horizontal milestone strip below it.
   Hovering (or tapping) a milestone spotlights the matching
   point on the chart; article headings are linked too.
   ============================================ */

const SP500_CHARTS = {};   // canvasId -> Chart instance

function setSpotlight(canvasId, label) {
    const chart = SP500_CHARTS[canvasId];
    if (!chart) return;
    if (chart.$spotlight === label) return;
    chart.$spotlight = label;
    chart.draw();
}

function buildMilestoneTimeline(canvasId, events) {
    const canvas = document.getElementById(canvasId);
    const chartWrap = canvas && canvas.closest('.sp500-chart-wrap');
    if (!chartWrap) return;

    const sorted = [...events].sort((a, b) => a.year - b.year);

    const strip = document.createElement('div');
    strip.className = 'sp500-timeline';

    sorted.forEach(event => {
        const item = document.createElement('button');
        item.type = 'button';
        item.className = 'sp500-tl-item ' + (event.type === 'bull' ? 'is-bull' : 'is-bear');
        item.innerHTML =
            '<span class="sp500-tl-year">' + Math.floor(event.year) + '</span>' +
            '<span class="sp500-tl-label">' + event.label + '</span>';
        item.addEventListener('mouseenter', () => setSpotlight(canvasId, event.label));
        item.addEventListener('mouseleave', () => setSpotlight(canvasId, null));
        item.addEventListener('focus', () => setSpotlight(canvasId, event.label));
        item.addEventListener('blur', () => setSpotlight(canvasId, null));
        // Tap toggle for touch devices
        item.addEventListener('click', () => {
            const chart = SP500_CHARTS[canvasId];
            const active = chart && chart.$spotlight === event.label;
            setSpotlight(canvasId, active ? null : event.label);
        });
        strip.appendChild(item);
    });

    chartWrap.insertAdjacentElement('afterend', strip);
}

